// src/utils/workloadFilters.js
//
// Предикаты фильтрации задач для дашборда загрузки и связанных экранов.
//
// Единственная точка правды «какие задачи участвуют в подсчёте часов».
// Меняется здесь - согласованно обновляются дашборд загрузки и модалка
// задач сотрудника, без риска, что цифры на двух экранах разойдутся.

/**
 * Активная задача: не в архиве и не отменена. Под неё считаются и
 * плановые часы (распределение по рабочим дням), и фактически учтённые
 * (logs). Закрытые задачи остаются - они тоже входят в загрузку, пока
 * не ушли в архив.
 */
export const isCountableTask = (task) =>
  !!task && !task.archived && task.status !== 'cancelled';