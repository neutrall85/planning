// src/utils/rejection.js
//
// Единое правило «что такое причина отклонения».
//
// Живёт здесь, а не в каждом сервисе: это доменное правило, а не
// локальная валидация. Сервисы принимают reason через публичный API
// (store.decideX(..., reason)), и каждый обязан нормализовать и
// проверить его одинаково. Иначе при смене формулировки ошибки или
// добавлении требования (например, минимальной длины) придётся править
// 4 файла и надеяться, что ничего не забыто.
//
// Возвращает:
//   - при approved === true: null (поле rejectionReason должно быть
//     сброшено - повторное одобрение не должно тянуть за собой старое
//     отклонение);
//   - при approved === false: trimmed-строку или бросает, если пусто.
export function normalizeRejectionReason(approved, reason) {
  if (approved) return null;
  const trimmed = String(reason ?? '').trim();
  if (!trimmed) {
    throw new Error('Причина отклонения обязательна');
  }
  return trimmed;
}