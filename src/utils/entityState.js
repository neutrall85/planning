// src/utils/entityState.js
import { addMonths, iso } from './date';

/**
 * Состояние сущности - «архивная» или нет.
 *
 * Закрытая или отменённая сущность считается архивной, даже если флаг
 * archived не выставлен. Так бывает у долгосрочных административных
 * проектов (longterm: true): их автоархивация обходит, статус остаётся
 * closed. И у только что закрытых задач, которые ещё моложе срока
 * автоархивации.
 *
 * Пользователь не различает «закрыт» и «в архиве» - для него это одно
 * состояние «выведен из работы». Поэтому правило должно работать по
 * смыслу, а не по технической детали: где-то archived выставляется
 * автоматикой, где-то нет, но поведение одинаковое.
 *
 * Заменяет прямые проверки `entity.archived` везде, где речь про
 * запрет правки/удаления/изменения статуса. Не применять там, где
 * речь именно про флаг архивации (см. TaskService.archiveOldTasks,
 * ProjectService - блок «архивация при закрытии»): там важен сам
 * переход, а не итоговое состояние.
 */
export const isArchived = (entity) =>
  !!entity && (
    entity.archived === true ||
    entity.status === 'closed' ||
    entity.status === 'cancelled'
  );

/**
 * Активная задача: показывать её в UI или нет.
 *
 * Правила:
 *   - не архивная - активная (это основной случай);
 *   - архивная, но закрыта недавно (в пределах окна переархивации) -
 *     тоже активная: пользователь ещё «помнит» её как рабочую,
 *     и прятать её из фильтров было бы неожиданно;
 *   - архивная и закрыта давно, либо архивная без даты закрытия -
 *     не активная.
 *
 * Окно переархивации - 3 месяца, то же значение используется в
 * TaskService.archiveOldTasks. Дублировать его в константу сейчас не
 * стоит: если решим менять - менять придётся синхронно в двух местах,
 * и это заметно при первом же ревью.
 *
 * НЕ ПУТАТЬ с isCountableTask (utils/workloadFilters). Семантика
 * предикатов разная, и объединять их нельзя:
 *   - isTaskActive     - «показывать в UI» (включает недавно закрытые);
 *   - isCountableTask  - «считать в загрузке» (исключает отменённые,
 *                        не смотрит на давность закрытия).
 *
 * Раньше функция жила в utils/date.js. Это было ошибкой места: она не
 * про даты, а про доменное состояние. Перенос сюда - к isArchived, у
 * которого та же предметная область.
 */
export const isTaskActive = (task) => {
  if (!task) return false;
  if (!task.archived) return true;
  if (task.closedAt) {
    const cutoff = addMonths(new Date(), -3);
    return task.closedAt >= iso(cutoff);
  }
  return false;
};