/**
 * Хелперы сборки опций для <Select>.
 *
 * Раньше в каждом фильтре повторялось одно и то же:
 *
 *     useMemo(() => [
 *       { value: 'all', label: 'Все' },
 *       ...Object.entries(MAP).map(([k, v]) => ({ value: k, label: v.label })),
 *     ], [])
 *
 * Здесь два варианта источника опций:
 *   - статическая карта-константа (PRIORITIES, PROJECT_STATUSES, ...);
 *   - динамический список из реквизита/стора (проекты, сотрудники, отделы).
 *
 * Оба всегда начинаются с пункта «все» (allLabel): в фильтрах проекта
 * пустой выбор всегда читается как «все», никогда как «ничего не выбрано».
 * Это правило живёт в одном месте - если решим поменять его (например,
 * убрать пункт «все» для какого-то фильтра), менять придётся здесь.
 */

/**
 * Опции из объекта-карты { код: { label } | 'строка' }.
 *
 * Второй аргумент - подпись пункта «все»; третьим можно передать
 * собственный извлекатель подписи, если запись карты сложнее
 * `{ label }` или строки.
 */
export const optionsFromMap = (map, allLabel, labelOf = (v) => v.label || v) => [
  { value: 'all', label: allLabel },
  ...Object.entries(map).map(([k, v]) => ({ value: k, label: labelOf(v) })),
];

/**
 * Опции из массива сущностей.
 *
 * toOption(item) возвращает пару { value, label } - форма у всех
 * источников разная (проект → код, сотрудник → «Фамилия Имя»,
 * отдел → название), поэтому единый маппер задаёт вызывающий.
 */
export const optionsFromList = (list, allLabel, toOption) => [
  { value: 'all', label: allLabel },
  ...list.map(toOption),
];