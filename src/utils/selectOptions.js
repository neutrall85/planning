/**
 * Хелперы сборки опций для <Select>.
 *
 * Здесь два варианта источника опций:
 *   - статическая карта-константа (PRIORITIES, PROJECT_STATUSES, ...);
 *   - динамический список из реквизита/стора (проекты, сотрудники, отделы).
 *
 * Оба всегда начинаются с пункта «все» (allLabel): в фильтрах проекта
 * пустой выбор читается как «все», никогда как «ничего не выбрано».
 * Это правило живёт здесь - если решим поменять его (например, убрать
 * пункт «все» для какого-то фильтра), менять придётся только в одном месте.
 *
 * Сортировка опций - не здесь, а в самом Select (см. sortOptions ниже).
 * Так правило одно на весь проект: вызывающий код порядок не задаёт,
 * а Select применяет его к любому источнику опций.
 */

/**
 * Служебные значения опций, которые всегда остаются на своих позициях:
 * плейсхолдер одиночного селекта (`''`) и модификаторы фильтров
 * («все» / «любые» / «без»). Сортируются только «настоящие» пункты,
 * остальное — фиксированный верх списка.
 *
 * Модификаторы приходят из optionsFromMap / optionsFromList, поэтому
 * правило должно быть общим. Без пиннинга «Все сотрудники» уехало бы
 * в середину алфавитного списка, а «Все КБ» — под «Вне КБ».
 */
const PINNED_VALUES = new Set(['', 'all', 'any', 'none']);

/**
 * Опции из объекта-карты { код: { label } | 'строка' }.
 *
 * Второй аргумент - подпись пункта «все»; третьим можно передать
 * собственный извлекатель подписи, если запись карты сложнее
 * `{ label }` или строки.
 */
export const optionsFromMap = (map, allLabel, labelOf = (v) => v.label || v) => [
  { value: 'all', label: allLabel },
  ...Object.entries(map).map(([k, v]) => ({ value: k, label: labelOf(v) })),
];

/**
 * Опции из массива сущностей.
 *
 * toOption(item) возвращает пару { value, label } - форма у всех
 * источников разная (проект → код, сотрудник → «Фамилия Имя»,
 * отдел → название), поэтому единый маппер задаёт вызывающий.
 */
export const optionsFromList = (list, allLabel, toOption) => [
  { value: 'all', label: allLabel },
  ...list.map(toOption),
];

/**
 * Сортирует опции выпадающего списка по алфавиту.
 *
 * - Опции с value из PINNED_VALUES сохраняют исходные позиции.
 * - Остальные сортируются по label через localeCompare с русской
 *   локалью: без явной локали «Ё» и регистр дают разный порядок в
 *   разных браузерах.
 *
 * Возвращает новый массив, исходный не мутирует. Порядок элементов с
 * одинаковым label сохраняется (Array#sort стабилен).
 */
export const sortOptions = (options) => {
  if (!Array.isArray(options) || options.length < 2) return options || [];
  const pinned = [];
  const sortable = [];
  for (const opt of options) {
    if (PINNED_VALUES.has(String(opt.value))) pinned.push(opt);
    else sortable.push(opt);
  }
  sortable.sort((a, b) => String(a.label).localeCompare(String(b.label), 'ru'));
  return [...pinned, ...sortable];
};